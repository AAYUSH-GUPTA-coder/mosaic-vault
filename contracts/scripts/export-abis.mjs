// Exports contract ABIs from Hardhat artifacts to lib/blockchain/abis/<ContractName>.ts
// as `export const <camelName>Abi = [...] as const;` plus index.ts (docs/CONTRACTS.md "ABI export").
// Run from contracts/: `node scripts/export-abis.mjs` (after `npx hardhat compile`).
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contractsRoot = resolve(here, "..");
const outDir = resolve(contractsRoot, "../lib/blockchain/abis");

const CONTRACTS = [
  ["CollateralRegistry", "contracts/CollateralRegistry.sol"],
  ["CollateralVault", "contracts/CollateralVault.sol"],
  ["MosaicLendingPool", "contracts/MosaicLendingPool.sol"],
  ["MosaicLendingEngine", "contracts/MosaicLendingEngine.sol"],
  ["MosaicLiquidationEngine", "contracts/MosaicLiquidationEngine.sol"],
  ["ChainlinkFeedOracleAdapter", "contracts/oracles/ChainlinkFeedOracleAdapter.sol"],
  ["TestPriceOracle", "contracts/oracles/TestPriceOracle.sol"],
  ["TestCollateralToken", "contracts/test/TestCollateralToken.sol"],
];

const camel = (n) => n.charAt(0).toLowerCase() + n.slice(1);
const artifact = (sol, name) => {
  const p = resolve(contractsRoot, "artifacts", sol, `${name}.json`);
  if (!existsSync(p)) throw new Error(`artifact missing: ${p} (run npx hardhat compile)`);
  return JSON.parse(readFileSync(p, "utf8"));
};
const header = "// AUTO-GENERATED by contracts/scripts/export-abis.mjs. Do not edit by hand.\n";
const emit = (name, abi) => `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;

mkdirSync(outDir, { recursive: true });

for (const [name, sol] of CONTRACTS) {
  const { abi } = artifact(sol, name);
  let body = header + emit(`${camel(name)}Abi`, abi);
  if (name === "ChainlinkFeedOracleAdapter") {
    // minimal AggregatorV3 surface used by the adapter and the UI (kept under its existing export name)
    const agg = artifact(sol, "IAggregatorV3").abi;
    body += "\n/** Minimal AggregatorV3 surface (Mezo BTC/USD precompile). */\n" + emit("aggregatorV3Abi", agg);
  }
  writeFileSync(resolve(outDir, `${name}.ts`), body);
  console.log(`wrote ${name}.ts (${abi.length} entries)`);
}

// shared.ts holds hand-maintained helper ABIs (oracleAdapterAbi, accessControlAbi, struct components) that
// other modules import. Keep it, but verify oracleAdapterAbi still matches IPriceOracleAdapter.
const sharedPath = resolve(outDir, "shared.ts");
const oracleIface = artifact("contracts/interfaces/IPriceOracleAdapter.sol", "IPriceOracleAdapter").abi;
if (existsSync(sharedPath)) {
  const shared = readFileSync(sharedPath, "utf8");
  for (const fn of oracleIface.filter((e) => e.type === "function").map((e) => e.name)) {
    if (!shared.includes(`name: "${fn}"`)) console.warn(`WARNING: shared.ts oracleAdapterAbi lacks ${fn}`);
  }
  for (const name of ["oracleAdapterAbi", "accessControlAbi"]) {
    if (!shared.includes(`export const ${name}`)) throw new Error(`shared.ts must export ${name}`);
  }
} else {
  // first run without the hand-written file: generate the two required helper ABIs from artifacts
  const ac = artifact("@openzeppelin/contracts/access/AccessControl.sol", "AccessControl").abi;
  writeFileSync(sharedPath, header + emit("oracleAdapterAbi", oracleIface) + "\n" + emit("accessControlAbi", ac));
  console.log("wrote shared.ts (generated)");
}

const index = `${header}export { erc20Abi } from "viem";
export { collateralRegistryAbi } from "./CollateralRegistry";
export { collateralVaultAbi } from "./CollateralVault";
export { mosaicLendingPoolAbi } from "./MosaicLendingPool";
export { mosaicLendingEngineAbi } from "./MosaicLendingEngine";
export { mosaicLiquidationEngineAbi } from "./MosaicLiquidationEngine";
export { chainlinkFeedOracleAdapterAbi, aggregatorV3Abi } from "./ChainlinkFeedOracleAdapter";
export { testPriceOracleAbi } from "./TestPriceOracle";
export { testCollateralTokenAbi } from "./TestCollateralToken";
export { oracleAdapterAbi, accessControlAbi } from "./shared";
`;
writeFileSync(resolve(outDir, "index.ts"), index);
console.log(`wrote index.ts -> ${outDir}`);
